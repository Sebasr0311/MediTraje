--   2. Tabla EPISODIO_ATENCION: Ciclo de vida asistencial hospitalario desacoplado de cita.
--   3. Tabla INGRESO_URGENCIA: Registro presencial de llegada a urgencias (idempotente, acepta NN y sin EPS).
--   4. Tabla IDENTIDAD_PROVISIONAL: Identificación temporal y reconciliación de pacientes NN indocumentados.
--   5. Tabla VALORACION_TRIAJE: Valoración clínica humana presencial I–V y PENDIENTE_VALORACION (inmutable, append-only).
--   6. Tabla ASIGNACION_ASISTENCIAL: Vínculo explícito de equipo asistencial (médico/enfermero) a episodio de urgencias.
--   7. Índices relacionales y privilegios mínimos para MEDITRIAJE_APP.
