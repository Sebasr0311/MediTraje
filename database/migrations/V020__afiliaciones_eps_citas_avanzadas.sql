-- -----------------------------------------------------------------------------
-- 1. TABLA: ENTIDAD_EPS
-- -----------------------------------------------------------------------------
CREATE TABLE ENTIDAD_EPS (
    ID NUMBER GENERATED ALWAYS AS IDENTITY,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    CODIGO_MINSALUD VARCHAR2(20 CHAR) NOT NULL,
    NOMBRE VARCHAR2(150 CHAR) NOT NULL,
    NIT VARCHAR2(20 CHAR),
    REGIMEN_HABITUAL VARCHAR2(30 CHAR) DEFAULT 'CONTRIBUTIVO' NOT NULL,
    ESTADO VARCHAR2(20 CHAR) DEFAULT 'ACTIVA' NOT NULL,
    CREADO_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_ENTIDAD_EPS PRIMARY KEY (ID),
    CONSTRAINT UQ_EPS_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT UQ_EPS_CODIGO UNIQUE (CODIGO_MINSALUD),
    CONSTRAINT CK_EPS_REGIMEN CHECK (REGIMEN_HABITUAL IN ('CONTRIBUTIVO', 'SUBSIDIADO', 'ESPECIAL', 'MIXTO')),
    CONSTRAINT CK_EPS_ESTADO CHECK (ESTADO IN ('ACTIVA', 'INACTIVA', 'LIQUIDACION'))
);

CREATE INDEX IX_EPS_CODIGO_ESTADO ON ENTIDAD_EPS (CODIGO_MINSALUD, ESTADO);

