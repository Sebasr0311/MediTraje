--   2. ATENCION: Acto médico profesional inmutable (ADR-008). Relación 1:1 con CITA.
--      Trigger TR_ATENCION_INMUTABILIDAD bloquea UPDATE de atenciones CERRADAS y DELETE total.
--   3. SIGNO_VITAL: Parámetros fisiológicos vinculados a la atención.
--      Trigger TR_SIGNO_VITAL_INMUTABILIDAD prohíbe INSERT/UPDATE/DELETE si la atención está CERRADA.
--   4. ATENCION_ENMIENDA: Aclaración append-only a atenciones cerradas (ADR-008).
--      Trigger TR_ENMIENDA_INMUTABILIDAD prohíbe UPDATE y DELETE, y exige que la atención esté CERRADA.
--   5. ALERGIA: Registro de hipersensibilidades del paciente.
--   6. Privilegios mínimos (ADR-012): MEDITRIAJE_APP no posee DELETE sobre ninguna tabla clínica,
